/** Seed the global sample templates + provision existing tenants (best-effort). */
export async function seedPrintTemplates(prisma: PrismaClient): Promise<void> {
  // ── 1. Global (tenant-less) sample templates ──
  const globals: Array<{ id: string; type: string }> = [];
  let createdGlobals = 0;
  for (const t of TEMPLATES) {
    let row = await prisma.pdfReportTemplate.findFirst({
      where: { tenantId: null, type: t.type, name: t.name, deletedAt: null },
      select: { id: true, type: true },
    });
    if (!row) {
      row = await prisma.pdfReportTemplate.create({
        data: {
          tenantId: null,
          branchId: null,
          type: t.type,
          name: t.name,
          isActive: true,
          meta: t.meta,
        },
        select: { id: true, type: true },
      });
      createdGlobals += 1;
    }
    globals.push(row);
  }
  console.log(
    `Seeded global print templates: ${createdGlobals} created (${TEMPLATES.length} in the set).`,
  );

  // ── 2. Best-effort: clone each global into every tenant + set config default ──
  // Tenant-scoped writes must run with the RLS tenant GUC set (mirrors
  // PrismaService.withTenant). Guarded per tenant so a fresh/empty DB or an RLS
  // hiccup never fails the whole seed.
  const tenants = await prisma.tenant.findMany({
    where: { deletedAt: null },
    select: { id: true },
  });
  if (tenants.length === 0) {
    console.log(
      'No tenants to provision print templates for (globals seeded).',
    );
    return;
  }

  let provisioned = 0;
  for (const tenant of tenants) {
    try {
      await prisma.$transaction(async (tx) => {
        await tx.$executeRawUnsafe(
          `SELECT set_config('app.current_tenant_id', '${tenant.id}', true)`,
        );
        for (const g of globals) {
          // Clone (idempotent via clonedFromId).
          let clone = await tx.pdfReportTemplate.findFirst({
            where: { tenantId: tenant.id, clonedFromId: g.id, deletedAt: null },
            select: { id: true },
          });
          if (!clone) {
            const src = TEMPLATES.find((t) => t.type === g.type)!;
            clone = await tx.pdfReportTemplate.create({
              data: {
                tenantId: tenant.id,
                branchId: null,
                clonedFromId: g.id,
                type: src.type,
                name: src.name,
                isActive: true,
                meta: src.meta,
              },
              select: { id: true },
            });
          }
          // Configuration default for this slot (idempotent).
          const cfg = await tx.pdfTemplateConfig.findFirst({
            where: {
              tenantId: tenant.id,
              branchId: null,
              slotKey: g.type,
              deletedAt: null,
            },
            select: { id: true },
          });
          if (cfg) {
            await tx.pdfTemplateConfig.update({
              where: { id: cfg.id },
              data: { templateId: clone.id },
            });
          } else {
            await tx.pdfTemplateConfig.create({
              data: {
                tenantId: tenant.id,
                branchId: null,
                slotKey: g.type,
                templateId: clone.id,
              },
            });
          }
        }
      });
      provisioned += 1;
    } catch (e) {
      console.warn(
        `Skipped print-template provisioning for tenant ${tenant.id}: ${(e as Error).message}`,
      );
    }
  }
  console.log(
    `Provisioned print templates + config defaults for ${provisioned}/${tenants.length} tenant(s).`,
  );
}
