/**
 * Seed one GLOBAL (SITE_ADMIN, tenant-less) classic PDF print template per
 * supported print `type`, then best-effort clone each into every existing tenant
 * and set it as that slot's Configuration default — so the template-driven Print
 * buttons have a ready, non-empty picker and every Mustache variable can be
 * verified end-to-end.
 *
 * Idempotent: skips a global that already exists (matched by tenant-null + type +
 * name); skips a tenant clone that already exists (matched by `clonedFromId`).
 * Each template's Header/Body/Footer HTML deliberately exercises EVERY variable
 * and `{{#each}}` section its context builder emits (see the B6 catalogue), so a
 * generated PDF visibly proves each token is replaced.
 */

/** Build a complete `meta` blob (defaults + the three HTML fragments). */
function meta(
  header: string,
  body: string,
  footer: string,
): Record<string, string> {
  return {
    ...PDF_TEMPLATE_META_DEFAULTS,
    default_font: 'helvetica',
    custom_css:
      'table{width:100%;border-collapse:collapse;font-size:9pt}td,th{border:1px solid #999;padding:3px;text-align:left}h2{margin:0}.muted{color:#555}.label{display:inline-block;border:1px dashed #333;padding:6px;margin:4px;width:220px}.barcode{font-family:monospace;font-size:14pt;letter-spacing:2px}',
    header_html: header,
    body_html: body,
    footer_html: footer,
  };
}

